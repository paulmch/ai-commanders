class HullMount:
    """One mount of a hull class: slot id, kind and its blocked-direction mask."""

    __slots__ = ("slot", "kind", "index", "mask", "open_fraction", "axis", "pos")

    def __init__(self, slot, kind, index, mask, open_fraction, axis, pos):
        self.slot = slot
        self.kind = kind            # 'gun' | 'pd' | 'spinal' | 'launcher'
        self.index = index          # position in the hull's mount list ('tur' order)
        self.mask = mask            # bytes, one per grid cell, 1 = blocked
        self.open_fraction = open_fraction
        self.axis = axis
        self.pos = pos


class HullMounts:
    """All mounts of one hull class, in file order."""

    __slots__ = ("hull", "mounts", "by_slot")

    def __init__(self, hull: str, mounts: List[HullMount]):
        self.hull = hull
        self.mounts = mounts
        self.by_slot = {m.slot: m for m in mounts}


def decode_mask(hex_string: str) -> bytes:
    """
    Hex string, one bit per grid cell, row-major by elevation cell from -90 up
    then azimuth cell from -180 up; cell i is bit (7 - i % 8) of byte i // 8
    (most significant bit first). Returns one byte (0/1) per cell.
    """
    raw = bytes.fromhex(hex_string)
    if len(raw) * 8 < _CELLS:
        raise ValueError(f"mask has {len(raw) * 8} bits, need {_CELLS}")
    out = bytearray(_CELLS)
    for i in range(_CELLS):
        out[i] = (raw[i >> 3] >> (7 - (i & 7))) & 1
    return bytes(out)


def encode_mask(cells) -> str:
    """Inverse of decode_mask (used by tests and fixtures)."""
    raw = bytearray((_CELLS + 7) // 8)
    for i in range(_CELLS):
        if cells[i]:
            raw[i >> 3] |= 1 << (7 - (i & 7))
    return raw.hex()


def parse_hull_mounts(data: dict) -> Dict[str, HullMounts]:
    grid = data.get("grid") or {}
    if (int(grid.get("az_cells", AZ_CELLS)) != AZ_CELLS
            or int(grid.get("el_cells", EL_CELLS)) != EL_CELLS
            or float(grid.get("az_step_deg", AZ_STEP_DEG)) != AZ_STEP_DEG
            or float(grid.get("el_step_deg", EL_STEP_DEG)) != EL_STEP_DEG):
        raise ValueError("hull_mounts grid is not the 5 degree 72 x 36 grid this engine reads")
    table: Dict[str, HullMounts] = {}
    for hull, spec in (data.get("hulls") or {}).items():
        mounts = []
        for index, m in enumerate(spec.get("mounts") or []):
            mounts.append(HullMount(
                slot=m["slot"], kind=m.get("kind", "gun"), index=index,
                mask=decode_mask(m["blocked"]),
                open_fraction=float(m.get("open_fraction", 0.0)),
                axis=tuple(float(v) for v in (m.get("axis") or (0.0, 0.0, 1.0))),
                pos=tuple(float(v) for v in (m.get("pos") or (0.0, 0.0, 0.0))),
            ))
        table[hull] = HullMounts(hull, mounts)
    return table


_CACHE: Dict[str, Dict[str, HullMounts]] = {}


def load_hull_mounts(path=None) -> Dict[str, HullMounts]:
    """The mount table of a file, loaded once per process ({} when absent)."""
    key = str(path or DEFAULT_PATH)
    table = _CACHE.get(key)
    if table is None:
        try:
            with open(key, "r", encoding="utf-8") as handle:
                table = parse_hull_mounts(json.load(handle))
        except FileNotFoundError:
            table = {}
        _CACHE[key] = table
    return table


