"""
Weapon arcs and turret traverse.

Every trainable weapon on a hull - coilgun batteries, heavy mounts, point
defence lasers - has directions it cannot fire in because the ship's own hull
is in the way, and a finite traverse rate. This module holds the data model
and the float-only helpers; the simulation (CombatSimulation._arcs_*) decides
WHETHER and WHEN a round or a beam leaves from them. It never touches the hit
roll, the lead calculation or evasion.

Body frame (shared with the viewer, see docs/pass-5-recording-additions.md):
    x = forward (nose), z = up (dorsal), y = z cross x (port)
    azimuth = atan2(y, x), 0 at the nose, positive to port, (-180, 180]
    elevation = asin(z), positive dorsal, [-90, 90]

Masks come from ``data/hull_mounts.json`` (generated by the viewer's hull kit
from the real hull geometry, keyed by hull class only): per mount a 72 x 36
grid of 5 degree cells, 1 = the weapon cannot fire in that direction. The file
is loaded once per process; a lookup is two trig calls and one index into a
``bytes`` object - no allocation.

Roll: ``kinematic_state.up`` is the engine's NAVIGATION up - evasion reads it
to pick jink and sidestep directions, so it must not change under this
mechanic. The hull's real attitude adds a roll angle about the thrust axis
(``ShipArcs.roll``) on top of it: body up = navigation up (orthonormalised
against forward) rotated about forward by ``roll``. Roll never changes where
the drive points, so it never changes motion.
"""

from __future__ import annotations

import json
import math
import os
from pathlib import Path
from typing import Dict, List, Optional

# ---------------------------------------------------------------------------
# Named constants (game design; reasoning in docs/pass-5-recording-additions.md)
# ---------------------------------------------------------------------------

# Traverse rates, degrees per second. A mount slews along the great circle.
#
# PD laser: a light beam director, not a gun house. It must be able to hand
# over between the rounds of one salvo (a few degrees apart: free) and to swing
# onto a second salvo from another quarter within one engine tick or two.
# 120 deg/s crosses a full hemisphere in 1.5 s; at the 1 s engine tick any
# retarget inside 120 deg costs no dwell at all and the far side costs one
# tick - 5% of the ~20 s a round spends inside the 250 km envelope at the
# 12 km/s closure floor. The pinned per-turret figures (one turret blinds
# ~5 km/s of closure) therefore hold for a turret that BEARS.
PD_TRAVERSE_DEG_S = 120.0
# Coilgun battery (80 t house): 90 degrees in 3 s. Fast against the 10 s
# in-salvo cadence - a battery that has to swing 90 degrees onto a new target
# loses at most one round of a salvo.
BATTERY_TRAVERSE_DEG_S = 30.0
# Light battery (40 t): 90 degrees in 2 s.
LIGHT_BATTERY_TRAVERSE_DEG_S = 45.0
# Heavy coilgun battery (160 t): 90 degrees in 6 s - "a few seconds to swing
# through 90 degrees", about half a salvo step; a heavy mount that is caught
# looking the wrong way gives up most of a round, and it still out-turns every
# hull that carries it (a battleship needs ~37 s for 90 degrees under thrust).
HEAVY_BATTERY_TRAVERSE_DEG_S = 15.0

TRAVERSE_DEG_S_BY_WEAPON = {
    "pd_laser": PD_TRAVERSE_DEG_S,
    "light_coilgun_mk3": LIGHT_BATTERY_TRAVERSE_DEG_S,
    "coilgun_mk3": BATTERY_TRAVERSE_DEG_S,
    "heavy_coilgun_mk3": HEAVY_BATTERY_TRAVERSE_DEG_S,
}

# A mount is "on" its wanted direction within this angle (the slew of the
# current tick is applied first: a mount that can finish its swing during the
# tick fires in it).
AIM_TOLERANCE_DEG = 0.5

# Roll to unmask. Roll torque comes from the RCS quads only (thrust vectoring
# cannot roll a ship). For a hull of length L and radius r the quads' lever
# arm is r instead of L/2 while the roll inertia is ~m r^2/2 against
# ~m L^2/12 in pitch: roll acceleration = pitch RCS acceleration x L/(3 r),
# about 3.3 for the fleet's L/r ~ 10. The roll RATE is capped at the same
# multiple of the RCS pitch rate cap.
ROLL_RCS_AUTHORITY_FACTOR = 3.3
# The roll goal is re-planned on this battle-time lattice (every ship on the
# same ticks, so mirrored fleets plan on the same instants).
ROLL_REPLAN_INTERVAL_S = 5.0
# Candidate roll offsets searched at each re-plan.
ROLL_CANDIDATE_STEP_DEG = 15.0
# Hysteresis: a new roll goal must bring at least this much more gun
# firepower (fraction of the hull's trainable gun energy) to bear than the
# current goal; any extra PD turret-on-torpedo pair always wins.
ROLL_GUN_HYSTERESIS_FRACTION = 0.15
# A roll is scored at the candidate angle and this far to either side of it,
# so the planner prefers attitudes that hold a target with margin.
ROLL_MARGIN_DEG = 7.5
ROLL_MARGIN_SAMPLES_RAD = (0.0, math.radians(ROLL_MARGIN_DEG), -math.radians(ROLL_MARGIN_DEG))
# ...and a new goal must win at least one WHOLE turret-on-torpedo pair (all
# of its samples) over the standing goal before the ship re-rolls. (Two
# samples - less than one pair - let every small shift of an inbound salvo's
# bearing flip the goal between two attitudes on alternate re-plans.)
ROLL_PD_HYSTERESIS_SAMPLES = len(ROLL_MARGIN_SAMPLES_RAD)
# A goal, once chosen, stands at least this long (battle time) before a
# re-plan may replace it: a hull that needs 70-250 s per 90 degrees of roll
# gains nothing from a goal that changes every 5 s.
ROLL_GOAL_COMMIT_S = 15.0
# A goal chosen for the guns alone (no PD gain) stands until the hull could
# have rolled there (its planned roll time) - otherwise a slow hull abandons
# a 135 degree roll after 15 s and 2 degrees and rolls back. A better PD
# answer to an inbound torpedo may still replace it after ROLL_GOAL_COMMIT_S.
# Inbound torpedoes this close (multiples of the PD envelope) drive the roll.
ROLL_PD_HORIZON_ENVELOPES = 2.0

# A mount masked this long while it has a target is reported (mount_masked).
MOUNT_MASKED_REPORT_S = 3.0

# Mount states recorded in the trace ('tur').
IDLE = 0        # no target / stowed
SLEWING = 1     # target in an open direction, still swinging onto it
ON_TARGET = 2   # on target and clear
MASKED = 3      # target masked by the ship's own hull (or outside the gimbal)

AZ_STEP_DEG = 5.0
EL_STEP_DEG = 5.0
AZ_CELLS = 72
EL_CELLS = 36
_CELLS = AZ_CELLS * EL_CELLS
_INV_STEP = 1.0 / math.radians(AZ_STEP_DEG)
_PI = math.pi
_HALF_PI = math.pi / 2.0
_SUBSTEP = math.radians(AZ_STEP_DEG) * 0.5

DEFAULT_PATH = Path(__file__).resolve().parent.parent / "data" / "hull_mounts.json"


def _env_flag(name: str, default: bool) -> bool:
    value = os.environ.get(name)
    if value is None or value == "":
        return default
    return value.strip().lower() not in ("0", "false", "off", "no")


# Defaults of the two simulation flags (CombatSimulation.weapon_arcs /
# .roll_to_unmask). The environment overrides exist for measurement only
# (flag on/off sweeps through tools that build their own simulation).
WEAPON_ARCS_DEFAULT = True
ROLL_TO_UNMASK_DEFAULT = True


def weapon_arcs_default() -> bool:
    return _env_flag("AIC_WEAPON_ARCS", WEAPON_ARCS_DEFAULT)


def roll_to_unmask_default() -> bool:
    return _env_flag("AIC_ROLL_TO_UNMASK", ROLL_TO_UNMASK_DEFAULT)


