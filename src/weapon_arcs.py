# Lookup and traverse (floats only)
# ---------------------------------------------------------------------------

def cell_index(bx: float, by: float, bz: float) -> int:
    """Grid cell of a body-frame unit direction."""
    ia = int((math.atan2(by, bx) + _PI) * _INV_STEP)
    if ia >= AZ_CELLS:
        ia = 0                  # azimuth +180 wraps into the first cell
    if bz >= 1.0:
        ie = EL_CELLS - 1
    elif bz <= -1.0:
        ie = 0
    else:
        ie = int((math.asin(bz) + _HALF_PI) * _INV_STEP)
        if ie >= EL_CELLS:
            ie = EL_CELLS - 1
    return ie * AZ_CELLS + ia


def az_el_deg(bx: float, by: float, bz: float):
    """(azimuth, elevation) in degrees of a body-frame unit direction."""
    return (math.degrees(math.atan2(by, bx)),
            math.degrees(math.asin(1.0 if bz > 1.0 else (-1.0 if bz < -1.0 else bz))))


class MountState:
    """Per-ship state of one mount: where it points, what it wants, slew state."""

    __slots__ = ("slot", "kind", "index", "mask", "rate", "ax", "ay", "az",
                 "trained", "state", "target_id", "wx", "wy", "wz", "has_want",
                 "masked_since", "masked_reported", "stamp", "fallback_id")

    def __init__(self, mount: HullMount, rate_deg_s: float):
        self.slot = mount.slot
        self.kind = mount.kind
        self.index = mount.index
        self.mask = mount.mask
        self.rate = math.radians(rate_deg_s)
        n = math.sqrt(sum(v * v for v in mount.axis)) or 1.0
        # Stowed along the mount axis until it is first trained.
        self.ax, self.ay, self.az = (mount.axis[0] / n, mount.axis[1] / n, mount.axis[2] / n)
        self.trained = False
        self.state = IDLE
        self.target_id = None
        self.wx = self.wy = self.wz = 0.0
        self.has_want = False
        self.masked_since = None
        self.masked_reported = False
        self.stamp = -1.0
        self.fallback_id = None     # enemy engaged this tick while the target is masked

    def bears(self, bx: float, by: float, bz: float) -> bool:
        """True when the mount can fire in this body-frame direction."""
        return not self.mask[cell_index(bx, by, bz)]

    def check(self, wx: float, wy: float, wz: float) -> int:
        """
        State toward a wanted direction WITHOUT moving the mount: for a
        second designation inside a tick in which the mount has already
        slewed (it moves at most once per tick).
        """
        self.wx, self.wy, self.wz = wx, wy, wz
        self.has_want = True
        if self.mask[cell_index(wx, wy, wz)]:
            self.state = MASKED
        else:
            dot = self.ax * wx + self.ay * wy + self.az * wz
            self.state = ON_TARGET if dot >= _COS_AIM_TOL else SLEWING
        return self.state

    def idle(self) -> None:
        self.state = IDLE
        self.target_id = None
        self.has_want = False

    def train(self, wx: float, wy: float, wz: float, dt: float) -> int:
        """
        Slew toward the wanted body-frame direction for ``dt`` seconds along
        the great circle and return the new state. A mount whose target is
        masked trains to the edge of its arc and waits there. ``dt == 0``
        (CombatSimulation.settle_arcs, before the shooting starts) puts a
        mount that has never been trained straight onto an open target, as
        after the approach; every other designation slews at the rate.
        """
        self.wx, self.wy, self.wz = wx, wy, wz
        self.has_want = True
        mask = self.mask
        want_blocked = mask[cell_index(wx, wy, wz)]
        if not self.trained:
            self.trained = True
            if not want_blocked and dt == 0.0:
                self.ax, self.ay, self.az = wx, wy, wz
                self.state = ON_TARGET
                return ON_TARGET
        ax, ay, az = self.ax, self.ay, self.az
        dot = ax * wx + ay * wy + az * wz
        if dot > 1.0:
            dot = 1.0
        elif dot < -1.0:
            dot = -1.0
        theta = math.acos(dot)
        step = self.rate * dt
        if not want_blocked:
            if theta <= step + _AIM_TOL:
                self.ax, self.ay, self.az = wx, wy, wz
                self.state = ON_TARGET
                return ON_TARGET
            self.ax, self.ay, self.az = _toward(ax, ay, az, wx, wy, wz, theta, step)
            self.state = SLEWING
            return SLEWING
        # Masked: creep toward the target in half-cell steps and stop at the
        # last direction that is still open.
        self.state = MASKED
        if mask[cell_index(ax, ay, az)]:
            return MASKED          # already resting on an edge it cannot cross
        travel = step if step < theta else theta
        done = 0.0
        while done < travel:
            inc = _SUBSTEP if travel - done > _SUBSTEP else travel - done
            nx, ny, nz = _toward(ax, ay, az, wx, wy, wz, theta - done, inc)
            if mask[cell_index(nx, ny, nz)]:
                break
            ax, ay, az = nx, ny, nz
            done += inc
        self.ax, self.ay, self.az = ax, ay, az
        return MASKED


_AIM_TOL = math.radians(AIM_TOLERANCE_DEG)
_COS_AIM_TOL = math.cos(_AIM_TOL)


def _toward(ax, ay, az, wx, wy, wz, theta, step):
    """Rotate unit a toward unit w (angle theta apart) by ``step`` radians."""
    if step >= theta:
        return wx, wy, wz
    s = math.sin(theta)
    if s < 1e-9:
        # Antiparallel: any great circle will do; take a fixed body-frame one.
        px, py, pz = (0.0, -az, ay) if abs(ax) < 0.9 else (-ay, ax, 0.0)
        n = math.sqrt(px * px + py * py + pz * pz) or 1.0
        c, sn = math.cos(step), math.sin(step) / n
        return ax * c + px * sn, ay * c + py * sn, az * c + pz * sn
    ka = math.sin(theta - step) / s
    kw = math.sin(step) / s
    return ax * ka + wx * kw, ay * ka + wy * kw, az * ka + wz * kw


class ShipArcs:
    """
    One ship's mounts and its hull attitude: the body frame of the current
    tick (nine floats), the roll angle about the thrust axis and its
    controller state.
    """

    __slots__ = ("hull", "mounts", "guns", "pd", "roll", "roll_rate", "roll_goal",
                 "goal_since", "goal_eta", "fx", "fy", "fz", "lx", "ly", "lz", "ux", "uy", "uz",
                 "frame_time")

    def __init__(self, hull: Optional[HullMounts], ship) -> None:
        self.hull = hull
        self.mounts: List[MountState] = []
        self.guns: Dict[str, MountState] = {}
        self.pd: List[Optional[MountState]] = []
        self.roll = 0.0
        self.roll_rate = 0.0
        self.roll_goal = 0.0
        self.goal_since = None      # battle time the standing goal was chosen
        self.goal_eta = 0.0         # ...and the roll time it was planned with (s)
        self.fx, self.fy, self.fz = 1.0, 0.0, 0.0
        self.lx, self.ly, self.lz = 0.0, 1.0, 0.0
        self.ux, self.uy, self.uz = 0.0, 0.0, 1.0
        self.frame_time = -1.0
        if hull is None:
            return
        weapons = getattr(ship, "weapons", None) or {}
        pd_states = getattr(ship, "point_defense", None) or []
        self.pd = [None] * len(pd_states)
        for mount in hull.mounts:
            if mount.kind == "pd":
                rate = PD_TRAVERSE_DEG_S
            else:
                ws = weapons.get(mount.slot)
                wtype = getattr(getattr(ws, "weapon", None), "weapon_type", None)
                rate = TRAVERSE_DEG_S_BY_WEAPON.get(wtype, BATTERY_TRAVERSE_DEG_S)
            state = MountState(mount, rate)
            self.mounts.append(state)
            if mount.kind == "pd":
                try:
                    n = int(mount.slot.rsplit("_", 1)[1])
                except (IndexError, ValueError):
                    continue
                if 0 <= n < len(self.pd):
                    self.pd[n] = state
                    pd_states[n].mount = state
            elif mount.kind in ("gun", "spinal"):
                ws = weapons.get(mount.slot)
                if ws is not None:
                    self.guns[mount.slot] = state
                    ws.mount = state

    def set_frame(self, forward, up, time_s: float) -> None:
        """Body frame for this tick from the navigation frame and the roll."""
        fx, fy, fz = forward.x, forward.y, forward.z
        ux, uy, uz = up.x, up.y, up.z
        # port = up x forward (orthonormalises a navigation up that is not
        # exactly perpendicular to forward)
        lx = uy * fz - uz * fy
        ly = uz * fx - ux * fz
        lz = ux * fy - uy * fx
        n = math.sqrt(lx * lx + ly * ly + lz * lz)
        if n < 1e-9:
            # forward parallel to up: take any perpendicular
            if abs(fz) < 0.9:
                lx, ly, lz = -fy, fx, 0.0
            else:
                lx, ly, lz = 0.0, fz, -fy
            n = math.sqrt(lx * lx + ly * ly + lz * lz) or 1.0
        lx, ly, lz = lx / n, ly / n, lz / n
        # dorsal = forward x port
        ux = fy * lz - fz * ly
        uy = fz * lx - fx * lz
        uz = fx * ly - fy * lx
        roll = self.roll
        if roll != 0.0:
            c, s = math.cos(roll), math.sin(roll)
            # roll about +x: port' = port cos + dorsal sin, dorsal' = dorsal cos - port sin
            lx, ly, lz, ux, uy, uz = (lx * c + ux * s, ly * c + uy * s, lz * c + uz * s,
                                      ux * c - lx * s, uy * c - ly * s, uz * c - lz * s)
        self.fx, self.fy, self.fz = fx, fy, fz
        self.lx, self.ly, self.lz = lx, ly, lz
        self.ux, self.uy, self.uz = ux, uy, uz
        self.frame_time = time_s

    def to_body(self, dx: float, dy: float, dz: float):
        """World unit direction -> body frame (x forward, y port, z dorsal)."""
        return (dx * self.fx + dy * self.fy + dz * self.fz,
                dx * self.lx + dy * self.ly + dz * self.lz,
                dx * self.ux + dy * self.uy + dz * self.uz)

    def to_world(self, bx: float, by: float, bz: float):
        return (bx * self.fx + by * self.lx + bz * self.ux,
                bx * self.fy + by * self.ly + bz * self.uy,
                bx * self.fz + by * self.lz + bz * self.uz)

    def trace(self) -> list:
        """Per-mount [az_deg, el_deg, state] in hull_mounts order ('tur')."""
        out = []
        for m in self.mounts:
            az, el = az_el_deg(m.ax, m.ay, m.az)
            out.append([round(az, 1), round(el, 1), m.state])
        return out


def rolled(by: float, bz: float, cos_phi: float, sin_phi: float):
    """Body (y, z) of a fixed world direction after the ship rolls by phi more."""
    return by * cos_phi + bz * sin_phi, bz * cos_phi - by * sin_phi


def roll_time_s(angle_rad: float, accel: float, max_rate: float) -> float:
    """Time to roll through an angle from rest, bang-bang with a rate cap."""
    angle = abs(angle_rad)
    if angle <= 1e-9:
        return 0.0
    if accel <= 0.0:
        return float("inf")
    t_tri = 2.0 * math.sqrt(angle / accel)
    if max_rate > 0.0 and 0.5 * accel * t_tri > max_rate:
        return angle / max_rate + max_rate / accel
    return t_tri
